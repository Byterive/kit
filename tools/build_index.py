#!/usr/bin/env python3
"""Generate INDEX.md in every folder that holds markdown files (stdlib only).

Usage: python tools/build_index.py [project_root]
Reads YAML-ish frontmatter (title, summary, keywords, status) from each .md file and
writes a generated INDEX.md per folder plus a root INDEX.md linking to child indexes.
INDEX.md files are generated: never edit them by hand.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SKIP = {".git", "node_modules", "Library", "Temp", "Logs", "obj", "bin",
                "__pycache__", ".venv", "venv", "vendor", "_inbox"}
FM = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)


def load_skip():
    skip = set(DEFAULT_SKIP)
    path = os.path.join(HERE, "budgets.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            skip |= set(json.load(f).get("skip_dirs", []))
    return skip


def git_ignored():
    """Absolute paths of git-ignored files and folders (empty set when git is missing), so private notes are never indexed."""
    try:
        out = subprocess.run(["git", "-C", ROOT, "ls-files", "-o", "-i", "--exclude-standard", "--directory"],
                             capture_output=True, text=True, timeout=30).stdout
    except Exception:
        return set()
    return {os.path.normpath(os.path.join(ROOT, line.strip().rstrip("/"))) for line in out.splitlines() if line.strip()}


IGN = git_ignored()


def parse(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    m = FM.match(text)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip("[]")
    return meta


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def main():
    skip = load_skip()
    dirs_with_index = []
    for cur, dirnames, files in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in skip and not d.startswith(".")
                             and os.path.normpath(os.path.join(cur, d)) not in IGN)
        mds = sorted(f for f in files if f.endswith(".md") and f != "INDEX.md"
                     and os.path.normpath(os.path.join(cur, f)) not in IGN)
        children = [d for d in dirnames if os.path.exists(os.path.join(cur, d))]
        rel = os.path.relpath(cur, ROOT)
        is_root = rel == "."
        if not mds and not is_root and not children:
            continue
        rows = []
        for f in mds:
            m = parse(os.path.join(cur, f))
            rows.append((f, m.get("title", f), m.get("summary", "MISSING SUMMARY"),
                         m.get("keywords", ""), m.get("status", "")))
        out = ["# Index: " + ("project root" if is_root else rel.replace(os.sep, "/")),
               "", "<!-- GENERATED by tools/build_index.py. Do not edit. -->", ""]
        if rows:
            out += ["| File | Summary | Keywords | Status |", "|---|---|---|---|"]
            for f, t, s, k, st in rows:
                out.append(f"| [{cell(t)}]({f}) | {cell(s)} | {cell(k)} | {cell(st)} |")
            out.append("")
        subs = [d for d in dirnames if has_md(os.path.join(cur, d), skip)]
        if subs:
            out += ["## Subfolders", ""]
            for d in subs:
                out.append(f"- [{d}/]({d}/INDEX.md)")
            out.append("")
        with open(os.path.join(cur, "INDEX.md"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(out))
        dirs_with_index.append(rel)
    print(f"build_index: wrote {len(dirs_with_index)} INDEX.md file(s)")


def has_md(path, skip):
    for cur, dirnames, files in os.walk(path):
        dirnames[:] = [d for d in dirnames if d not in skip and not d.startswith(".")
                       and os.path.normpath(os.path.join(cur, d)) not in IGN]
        if any(f.endswith(".md") and f != "INDEX.md" and os.path.normpath(os.path.join(cur, f)) not in IGN for f in files):
            return True
    return False


if __name__ == "__main__":
    main()
